def main():
    is_enrolled = True
    has_submitted = False
    
    print("is_enrolled:", is_enrolled)
    print("has_submitted:", has_submitted)
    print("is_enrolled AND has_submitted:", is_enrolled and has_submitted)
    print("is_enrolled OR has_submitted:", is_enrolled or has_submitted)
    print("NOT has_submitted:", not has_submitted)

if __name__ == "__main__":
    main()